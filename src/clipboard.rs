//! Reading and writing the macOS clipboard, and watching it for new copies.

use std::thread;
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2_app_kit::{NSPasteboard, NSWorkspace};
use objc2_foundation::{NSData, NSString};

use crate::history::NewImage;
use crate::images;

/// macOS has no "clipboard changed" notification, so the watcher checks this often.
const POLL_INTERVAL: Duration = Duration::from_millis(300);

/// Password managers and similar apps tag secret or throwaway copies with these markers so that
/// clipboard history leaves them out (convention from nspasteboard.org).
const SKIPPED_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
];

/// Larger copies, such as a whole log file, are not saved.
const MAX_TEXT_BYTES: usize = 1024 * 1024;
const MAX_IMAGE_BYTES: usize = 25 * 1024 * 1024;

// The clipboard types Clippy reads and writes.
const TEXT: &str = "public.utf8-plain-text";
const PNG: &str = "public.png";
const TIFF: &str = "public.tiff";
const FILE: &str = "public.file-url";

/// Some apps put their own bundle identifier on the clipboard under this type when they copy
/// (convention from nspasteboard.org).
const SOURCE_TYPE: &str = "org.nspasteboard.source";

/// Clippy's own bundle identifier, which must match `CFBundleIdentifier` in scripts/bundle.sh.
const CLIPPY: &str = "local.clippy";

pub struct Copied {
    pub content: CopiedContent,
    /// Bundle identifier of the app the copy came from, when known.
    pub source_app: Option<String>,
}

pub enum CopiedContent {
    Text(String),
    Image(NewImage),
}

/// Calls `on_copy` on a background thread each time text or an image is copied anywhere on the Mac.
/// Whatever is on the clipboard when the watcher starts is not reported.
pub fn watch(on_copy: impl Fn(Copied) + Send + 'static) {
    thread::spawn(move || {
        let mut last_seen = autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount());
        loop {
            thread::sleep(POLL_INTERVAL);
            // Without a pool, every macOS call on this thread would leak a little memory.
            let copied = autoreleasepool(|_| {
                let pasteboard = NSPasteboard::generalPasteboard();
                let change_count = pasteboard.changeCount();
                if change_count == last_seen {
                    return None;
                }
                last_seen = change_count;
                read_copy(&pasteboard)
            });
            if let Some(copied) = copied {
                on_copy(copied);
            }
        }
    });
}

/// Puts `text` on the clipboard, ready to paste with ⌘V.
pub fn write_text(text: &str) {
    let pasteboard = NSPasteboard::generalPasteboard();
    pasteboard.clearContents();
    pasteboard.setString_forType(&NSString::from_str(text), &NSString::from_str(TEXT));
    sign_as_clippy(&pasteboard);
}

/// Puts a PNG image on the clipboard, ready to paste with ⌘V.
pub fn write_png(png: &[u8]) {
    put_png(&NSPasteboard::generalPasteboard(), png);
}

fn put_png(pasteboard: &NSPasteboard, png: &[u8]) {
    pasteboard.clearContents();
    pasteboard.setData_forType(Some(&NSData::with_bytes(png)), &NSString::from_str(PNG));
    sign_as_clippy(pasteboard);
}

/// Marks a copy as Clippy's own, so the item keeps showing the app it first came from.
fn sign_as_clippy(pasteboard: &NSPasteboard) {
    pasteboard.setString_forType(&NSString::from_str(CLIPPY), &NSString::from_str(SOURCE_TYPE));
}

fn read_copy(pasteboard: &NSPasteboard) -> Option<Copied> {
    let types: Vec<String> = pasteboard.types()?.iter().map(|t| t.to_string()).collect();
    let content = match kind_to_save(&types)? {
        Kind::Text => {
            let text = pasteboard.stringForType(&NSString::from_str(TEXT))?.to_string();
            if text.trim().is_empty() || text.len() > MAX_TEXT_BYTES {
                return None;
            }
            CopiedContent::Text(text)
        }
        Kind::Image(image_type) => {
            let data = pasteboard.dataForType(&NSString::from_str(image_type))?;
            if data.length() > MAX_IMAGE_BYTES {
                return None;
            }
            CopiedContent::Image(images::prepare_image(&data, image_type == PNG)?)
        }
    };
    let named = types
        .iter()
        .any(|t| t == SOURCE_TYPE)
        .then(|| pasteboard.stringForType(&NSString::from_str(SOURCE_TYPE)))
        .flatten()
        .map(|id| id.to_string());
    let frontmost = NSWorkspace::sharedWorkspace()
        .frontmostApplication()
        .and_then(|app| app.bundleIdentifier())
        .map(|id| id.to_string());
    Some(Copied { content, source_app: pick_source_app(named, frontmost) })
}

/// The app that names itself on the clipboard wins. Otherwise the copy is credited to the app in
/// front, which is where copying almost always happens. Copies made by Clippy credit nobody, so
/// the item keeps the app it was first copied from.
fn pick_source_app(named: Option<String>, frontmost: Option<String>) -> Option<String> {
    named.or(frontmost).filter(|app| app != CLIPPY)
}

#[derive(Debug, PartialEq)]
enum Kind {
    Text,
    /// Holds the clipboard type to read the image from.
    Image(&'static str),
}

/// Decides from the list of types alone, so secret and unsupported copies are never read at all.
fn kind_to_save(types: &[String]) -> Option<Kind> {
    let has = |wanted: &str| types.iter().any(|t| t == wanted);
    if SKIPPED_TYPES.iter().any(|t| has(t)) {
        return None;
    }
    // Apps that put both on the clipboard, such as a picture of copied table cells, are saved as text.
    if has(TEXT) {
        return Some(Kind::Text);
    }
    // Copying a file in Finder also puts the file's icon on the clipboard, which is not a picture
    // the user meant to copy.
    if has(FILE) {
        return None;
    }
    [PNG, TIFF].into_iter().find(|t| has(t)).map(Kind::Image)
}

#[cfg(test)]
mod tests {
    use super::*;
    use objc2::rc::Retained;
    use objc2_app_kit::NSBitmapImageRep;

    /// A 40 × 30 orange PNG.
    const ORANGE_PNG: &[u8] = &[
        0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d,
        0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00, 0x28, 0x00, 0x00, 0x00, 0x1e,
        0x08, 0x02, 0x00, 0x00, 0x00, 0xd1, 0xbf, 0xcb, 0x8a, 0x00, 0x00, 0x00,
        0x2a, 0x49, 0x44, 0x41, 0x54, 0x78, 0xda, 0xed, 0xcd, 0x31, 0x0d, 0x00,
        0x00, 0x08, 0x03, 0xb0, 0xc9, 0x41, 0x22, 0xee, 0x41, 0x06, 0x1c, 0x4d,
        0xfa, 0x37, 0xd3, 0x75, 0x22, 0x62, 0xb1, 0x58, 0x2c, 0x16, 0x8b, 0xc5,
        0x62, 0xb1, 0x58, 0x2c, 0xfe, 0x1b, 0x2f, 0x1c, 0xb7, 0x99, 0xba, 0xf2,
        0xf8, 0x91, 0xb3, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae,
        0x42, 0x60, 0x82,
    ];

    /// A clipboard of the test's own, so tests never touch what the user has copied. macOS
    /// discards it when the test ends.
    struct PrivateClipboard(Retained<NSPasteboard>);

    impl PrivateClipboard {
        fn new() -> Self {
            Self(NSPasteboard::pasteboardWithUniqueName())
        }

        fn holding(self, data_type: &str, data: &NSData) -> Self {
            self.0.clearContents();
            self.0.setData_forType(Some(data), &NSString::from_str(data_type));
            self
        }

        fn read_image(&self) -> (NewImage, Option<String>) {
            match read_copy(&self.0) {
                Some(Copied { content: CopiedContent::Image(image), source_app }) => (image, source_app),
                _ => panic!("no image was read from the clipboard"),
            }
        }
    }

    impl Drop for PrivateClipboard {
        fn drop(&mut self) {
            let _: () = unsafe { objc2::msg_send![&*self.0, releaseGlobally] };
        }
    }

    #[test]
    fn reads_a_copied_png_with_its_size_and_a_thumbnail() {
        let clipboard = PrivateClipboard::new().holding(PNG, &NSData::with_bytes(ORANGE_PNG));
        let (image, _) = clipboard.read_image();
        assert_eq!(image.png, ORANGE_PNG);
        assert_eq!((image.width, image.height), (40, 30));
        assert_eq!((image.thumbnail.width, image.thumbnail.height), (40, 30));
        // Orange, allowing for small changes from color matching.
        let [r, g, b, a] = image.thumbnail.pixels[..4] else { unreachable!() };
        assert!(r > 230 && (90..150).contains(&g) && b < 80 && a == 255, "got {r} {g} {b} {a}");
    }

    #[test]
    fn keeps_a_copied_tiff_as_png() {
        let tiff = NSBitmapImageRep::imageRepWithData(&NSData::with_bytes(ORANGE_PNG)).unwrap().TIFFRepresentation().unwrap();
        let clipboard = PrivateClipboard::new().holding(TIFF, &tiff);
        let (image, _) = clipboard.read_image();
        assert!(image.png.starts_with(b"\x89PNG"));
        assert_eq!((image.width, image.height), (40, 30));
    }

    #[test]
    fn an_image_clippy_puts_back_reads_back_unchanged_and_credits_no_app() {
        let clipboard = PrivateClipboard::new();
        put_png(&clipboard.0, ORANGE_PNG);
        let (image, source_app) = clipboard.read_image();
        assert_eq!(image.png, ORANGE_PNG);
        assert_eq!(source_app, None);
    }

    fn kind(names: &[&str]) -> Option<Kind> {
        kind_to_save(&names.iter().map(|name| name.to_string()).collect::<Vec<_>>())
    }

    #[test]
    fn saves_plain_text_copies() {
        assert_eq!(kind(&[TEXT, "public.html"]), Some(Kind::Text));
    }

    #[test]
    fn saves_copied_images() {
        assert_eq!(kind(&[PNG]), Some(Kind::Image(PNG)));
        assert_eq!(kind(&[TIFF]), Some(Kind::Image(TIFF)));
    }

    #[test]
    fn reads_an_image_offered_in_several_formats_as_png() {
        assert_eq!(kind(&[TIFF, PNG]), Some(Kind::Image(PNG)));
    }

    #[test]
    fn a_copy_with_both_text_and_an_image_is_saved_as_text() {
        assert_eq!(kind(&[PNG, TEXT]), Some(Kind::Text));
    }

    #[test]
    fn skips_files_copied_in_finder() {
        assert_eq!(kind(&[FILE, TIFF]), None);
    }

    #[test]
    fn skips_copies_with_neither_text_nor_an_image() {
        assert_eq!(kind(&["com.example.private-format"]), None);
    }

    #[test]
    fn skips_passwords_marked_secret_by_a_password_manager() {
        assert_eq!(kind(&[TEXT, "org.nspasteboard.ConcealedType"]), None);
    }

    #[test]
    fn skips_text_marked_as_temporary() {
        assert_eq!(kind(&[TEXT, "org.nspasteboard.TransientType"]), None);
    }

    #[test]
    fn skips_images_marked_secret() {
        assert_eq!(kind(&[PNG, "org.nspasteboard.ConcealedType"]), None);
    }

    fn app(id: &str) -> Option<String> {
        Some(id.to_string())
    }

    #[test]
    fn credits_the_copy_to_the_app_in_front() {
        assert_eq!(pick_source_app(None, app("com.apple.Safari")), app("com.apple.Safari"));
    }

    #[test]
    fn an_app_that_names_itself_on_the_clipboard_wins_over_the_app_in_front() {
        assert_eq!(pick_source_app(app("com.example.Sync"), app("com.apple.Safari")), app("com.example.Sync"));
    }

    #[test]
    fn copies_made_by_clippy_itself_credit_no_app() {
        assert_eq!(pick_source_app(app(CLIPPY), app("com.apple.Safari")), None);
        assert_eq!(pick_source_app(None, app(CLIPPY)), None);
    }
}
